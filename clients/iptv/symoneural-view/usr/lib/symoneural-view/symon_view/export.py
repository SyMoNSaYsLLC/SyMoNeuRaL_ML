"""Data export in multiple formats."""

from __future__ import annotations

import csv
import json
import logging
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)


class DataExporter:
    """Export data in multiple formats."""
    
    def __init__(self, export_dir: Path | str) -> None:
        self.export_dir = Path(export_dir)
        self.export_dir.mkdir(parents=True, exist_ok=True)
    
    def export_m3u(self, channels: list[dict], filepath: Path | str) -> bool:
        """Export to M3U format."""
        try:
            filepath = Path(filepath)
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write("#EXTM3U\n")
                f.write(f"# Generated by SyMoNeuRaL v2.0 on {datetime.now().isoformat()}\n\n")
                
                for channel in channels:
                    # Build EXTINF line
                    extinf_parts = ["-1"]
                    
                    if channel.get('tvg_id'):
                        extinf_parts.append(f'tvg-id="{channel["tvg_id"]}"')
                    
                    if channel.get('logo'):
                        extinf_parts.append(f'tvg-logo="{channel["logo"]}"')
                    
                    if channel.get('group'):
                        extinf_parts.append(f'group-title="{channel["group"]}"')
                    
                    extinf_line = f"#EXTINF:{','.join(extinf_parts)},{channel.get('name', 'Unknown')}\n"
                    f.write(extinf_line)
                    
                    if channel.get('url'):
                        f.write(f"{channel['url']}\n")
            
            logger.info(f"Exported {len(channels)} channels to {filepath}")
            return True
        
        except Exception as e:
            logger.error(f"M3U export failed: {e}")
            return False
    
    def export_json(self, channels: list[dict], filepath: Path | str) -> bool:
        """Export to JSON format."""
        try:
            filepath = Path(filepath)
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump({
                    "metadata": {
                        "generated": datetime.now().isoformat(),
                        "count": len(channels),
                        "version": "2.0"
                    },
                    "channels": channels
                }, f, indent=2, ensure_ascii=False)
            
            logger.info(f"Exported {len(channels)} channels to JSON")
            return True
        
        except Exception as e:
            logger.error(f"JSON export failed: {e}")
            return False
    
    def export_csv(self, channels: list[dict], filepath: Path | str,
                  fields: list[str] | None = None) -> bool:
        """Export to CSV format."""
        try:
            filepath = Path(filepath)
            if not fields:
                fields = ['name', 'group', 'url', 'logo', 'tvg_id']
            
            with open(filepath, 'w', newline='', encoding='utf-8') as f:
                writer = csv.DictWriter(f, fieldnames=fields)
                writer.writeheader()
                
                for channel in channels:
                    row = {field: channel.get(field, '') for field in fields}
                    writer.writerow(row)
            
            logger.info(f"Exported {len(channels)} channels to CSV")
            return True
        
        except Exception as e:
            logger.error(f"CSV export failed: {e}")
            return False
    
    def export_xmltv(self, epg_data: dict[str, list[dict]], filepath: Path | str) -> bool:
        """Export to XMLTV format."""
        try:
            filepath = Path(filepath)
            root = ET.Element('tv')
            root.set('generator-info-name', 'SyMoNeuRaL v2.0')
            
            # Add channels
            for channel_id in epg_data.keys():
                channel_elem = ET.SubElement(root, 'channel')
                channel_elem.set('id', channel_id)
                
                display_name = ET.SubElement(channel_elem, 'display-name')
                display_name.text = channel_id
            
            # Add programmes
            for channel_id, programmes in epg_data.items():
                for prog in programmes:
                    prog_elem = ET.SubElement(root, 'programme')
                    prog_elem.set('channel', channel_id)
                    prog_elem.set('start', prog.get('start', ''))
                    prog_elem.set('stop', prog.get('stop', ''))
                    
                    if prog.get('title'):
                        title = ET.SubElement(prog_elem, 'title')
                        title.text = prog['title']
                    
                    if prog.get('description'):
                        desc = ET.SubElement(prog_elem, 'desc')
                        desc.text = prog['description']
            
            tree = ET.ElementTree(root)
            tree.write(filepath, encoding='utf-8', xml_declaration=True)
            
            logger.info(f"Exported XMLTV to {filepath}")
            return True
        
        except Exception as e:
            logger.error(f"XMLTV export failed: {e}")
            return False
    
    def export_kodi_playlist(self, channels: list[dict], filepath: Path | str) -> bool:
        """Export as Kodi playlist."""
        try:
            filepath = Path(filepath)
            root = ET.Element('playlist')
            root.set('version', '1')
            
            for i, channel in enumerate(channels, 1):
                item = ET.SubElement(root, 'item')
                item.set('id', str(i))
                
                name = ET.SubElement(item, 'name')
                name.text = channel.get('name', 'Unknown')
                
                if channel.get('url'):
                    path = ET.SubElement(item, 'path')
                    path.text = channel['url']
                
                if channel.get('logo'):
                    thumb = ET.SubElement(item, 'thumb')
                    thumb.text = channel['logo']
            
            tree = ET.ElementTree(root)
            tree.write(filepath, encoding='utf-8', xml_declaration=True)
            
            logger.info(f"Exported Kodi playlist to {filepath}")
            return True
        
        except Exception as e:
            logger.error(f"Kodi export failed: {e}")
            return False
    
    def auto_backup(self, data: dict) -> Path | None:
        """Auto-backup important data."""
        try:
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            backup_file = self.export_dir / f"backup_{timestamp}.json"
            
            with open(backup_file, 'w', encoding='utf-8') as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
            
            logger.info(f"Backup created: {backup_file}")
            return backup_file
        
        except Exception as e:
            logger.error(f"Backup failed: {e}")
            return None